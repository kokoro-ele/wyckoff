const dictionaries: Record<Lang, Record<string, string>> = { zh, en };

function detectLang(): Lang {
  if (typeof window === "undefined") return "zh";
  const fromUrl = new URLSearchParams(window.location.search).get("lang");
  if (fromUrl === "zh" || fromUrl === "en") return fromUrl;
  const saved = window.localStorage.getItem("wyckoff:lang");
  if (saved === "zh" || saved === "en") return saved;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

let currentLang: Lang = detectLang();

export function setCurrentLang(lang: Lang) {
  currentLang = lang;
  if (typeof document !== "undefined") document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
}

function format(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`));
}

export function translate(key: string, vars?: Record<string, string | number>): string {
  const dictionary = dictionaries[currentLang] ?? zh;
  return format(dictionary[key] ?? zh[key] ?? key, vars);
}

export function currentLanguage(): Lang {
  return currentLang;
}

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nValue | undefined>(undefined);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => detectLang());

  useEffect(() => {
    setCurrentLang(lang);
    window.localStorage.setItem("wyckoff:lang", lang);
    try {
      const secure = window.location.protocol === "https:" ? "; Secure" : "";
      document.cookie = `wyckoff_lang=${lang}; Path=/; Max-Age=31536000; SameSite=Lax${secure}`;
    } catch {
      /* cookies can be disabled in private webviews */
    }
  }, [lang]);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    const url = new URL(window.location.href);
    if (url.searchParams.has("lang")) {
      url.searchParams.delete("lang");
      window.history.replaceState({}, "", url);
    }
  }, []);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => translate(key, vars),
    // lang is captured through the provider state; the function identity must
    // change so memoized children re-render with the new dictionary.
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
